import fs from 'node:fs';
const checks=[]; const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
const read=(p)=>fs.readFileSync(p,'utf8');
const page=read('apps/web/src/modules/platform/ui/pages/PlatformAdmin.jsx');
const shell=read('apps/web/src/layout/PlatformShell.jsx');
const api=read('apps/api/src/modules/platform/api/platformAdmin.js');
const schema=read('apps/api/prisma/schema.prisma');
const tabs=['overview','companies','subscriptions','renewals','trials','billing','users','health','support','plans','modules','integrations','revenue','system','security','audit','settings'];
for(const tab of tabs)add(`UI tab ${tab}`,page.includes(`'${tab}'`)||shell.includes(`tab:'${tab}'`));
for(const route of ['/dashboard','/companies','/subscriptions','/renewals','/trials','/plans','/modules','/billing','/revenue','/users','/support','/integrations','/security','/audit','/settings','/system'])add(`API ${route}`,api.includes(`'${route}'`)||api.includes(`\`${route}`));
add('MFA platform session',api.includes('requirePlatformSession'));
add('Reauth critical actions',api.includes('requireRecentReauth(600)'));
add('Platform settings model',schema.includes('model PlatformSetting'));
add('Support ticket model',schema.includes('model PlatformSupportTicket'));
add('Tenant ERP isolated',shell.includes('Control Plane')&&!shell.includes('Compras')&&!shell.includes('Inventario'));
const failed=checks.filter(x=>!x.ok);
for(const c of checks)console.log(`${c.ok?'PASS':'FAIL'}  ${c.name}`);
console.log(`\nPlatform Control Plane v13.3.0: ${checks.length-failed.length}/${checks.length} PASS`);
if(failed.length)process.exit(1);
