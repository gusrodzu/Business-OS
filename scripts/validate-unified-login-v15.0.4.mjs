import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const auth=read('apps/api/src/modules/core/api/auth.js');
const login=read('apps/web/src/pages/Login.jsx');
const context=read('apps/web/src/auth/AuthContext.jsx');
const protectedRoute=read('apps/web/src/auth/ProtectedRoute.jsx');
const app=read('apps/web/src/App.jsx');
const checks=[]; const add=(n,o)=>checks.push({n,o:Boolean(o)});
add('Single credential endpoint', auth.includes("router.post('/login'") && !auth.includes("z.enum(['erp', 'platform'])"));
add('Backend detects platform permission', auth.includes('const platform = isPlatformAdmin(user)'));
add('Platform account enters MFA automatically', auth.includes('if (platform)') && auth.includes('mfaRequired') && auth.includes('mfaSetupRequired'));
add('ERP account requires active tenant', auth.includes('tenantCompanyOk') && auth.includes('TENANT_REQUIRED'));
add('ERP token emitted automatically', auth.includes("createSessionToken(user, {kind: 'erp'})"));
add('Platform token remains 45m + MFA', auth.includes("kind === 'platform' ? '45m' : '8h'") && auth.includes("kind: 'platform', mfa: true"));
add('Client sends no requested auth context', !context.includes('context: platform') && !context.includes("context: platform ? 'platform' : 'erp'"));
add('Login handles MFA setup', login.includes('mfaSetupRequired') && login.includes("setStep('setup')"));
add('Login handles MFA verify', login.includes('mfaRequired') && login.includes("setStep('verify')"));
add('Login routes platform automatically', login.includes("result.sessionKind === 'platform' ? '/admin-saas'"));
add('Login routes ERP automatically', login.includes("const erpTarget"));
add('Protected routes use one login', !protectedRoute.includes('/admin-login'));
add('Legacy admin-login is alias only', app.includes('path="/admin-login"') && app.includes('to="/login"'));
add('Platform idle returns to unified login', context.includes("window.location.assign('/login?reason=idle')"));
const failed=checks.filter(x=>!x.o);
for(const c of checks) console.log(`${c.o?'PASS':'FAIL'}  ${c.n}`);
console.log(`\nUnified Login v15.0.4: ${checks.length-failed.length}/${checks.length} PASS`);
process.exit(failed.length?1:0);
