import assert from 'node:assert/strict';
import {test} from 'node:test';
import {webcrypto} from 'node:crypto';
import {offlineDemoRequest,resetOfflineDemo} from '../apps/web/src/offlineDemo.js';
const memory=new Map();
globalThis.localStorage={getItem:key=>memory.get(key)??null,setItem:(key,value)=>memory.set(key,String(value)),removeItem:key=>memory.delete(key)};
if(!globalThis.crypto)Object.defineProperty(globalThis,'crypto',{value:webcrypto});
const request=(path,method='GET',body,params)=>offlineDemoRequest(path,{method,body,params});
test('Calendar demo CRUD persists and includes overlapping events',async()=>{
  resetOfflineDemo();
  const {employees,types,priorities}=await request('/agenda/meta');
  assert.ok(Array.isArray(types)&&types.length>0);
  assert.ok(Array.isArray(priorities)&&priorities.length>0);
  assert.ok(employees.length);
  const body={title:'QA calendario',description:'Evento de prueba',startAt:'2026-11-25T15:00:00Z',endAt:'2026-11-27T16:00:00Z',allDay:false,priority:'HIGH',status:'ACTIVE',reminderMinutes:30,assigneeEmployeeId:employees[0].id};
  const {event}=await request('/agenda/events','POST',body);
  const path='/agenda/events/'+event.id;
  assert.equal((await request(path)).event.title,body.title);
  const range={from:'2026-11-26T00:00:00Z',to:'2026-11-26T23:59:59Z'};
  const list=()=>request('/agenda','GET',undefined,range);
  assert.ok((await list()).items.some(row=>row.rawId===event.id));
  await request(path,'PUT',{...body,title:'QA actualizado',reminderMinutes:null});
  assert.equal((await request(path)).event.title,'QA actualizado');
  await request(path+'/status','PATCH',{status:'COMPLETED'});
  assert.equal((await request(path)).event.status,'COMPLETED');
  await request(path+'/status','PATCH',{status:'ACTIVE'});
  assert.equal((await request(path)).event.status,'ACTIVE');
  await assert.rejects(request(path,'PUT',{...body,endAt:'2026-11-20T00:00:00Z'}));
  await assert.rejects(request(path,'PUT',{...body,assigneeEmployeeId:'invalid-employee'}));
  await request(path,'DELETE');
  assert.ok(!(await list()).items.some(row=>row.rawId===event.id));
  await assert.rejects(request(path));
  resetOfflineDemo();
});
