import fs from 'node:fs'; import path from 'node:path';
const root=process.cwd(); const read=p=>fs.readFileSync(path.join(root,p),'utf8'); const checks=[]; const check=(n,o)=>checks.push([n,!!o]);
const md=read('apps/web/src/design-system/styles/md3-foundation.css'); const rollout=read('apps/web/src/design-system/styles/md3-full-rollout.css');
check('Focus visible global',md.includes(':focus-visible'));
check('Reduced motion',rollout.includes('prefers-reduced-motion'));
check('Preferencia de contraste',rollout.includes('prefers-contrast:more'));
check('Touch targets coarse pointer',rollout.includes('--bb-md3-touch-target:48px'));
const dialog=read('apps/web/src/design-system/components/Dialog.jsx');
check('Dialog role dialog',dialog.includes('role="dialog"'));
check('Dialog aria-modal',dialog.includes('aria-modal="true"'));
check('Dialog cierra con Escape',dialog.includes("e.key==='Escape'"));
check('Dialog focus trap Tab',dialog.includes("e.key==='Tab'"));
check('Dialog restaura foco',dialog.includes('prior?.focus?.()'));
const drawer=read('apps/web/src/design-system/components/Drawer.jsx');
check('Drawer role dialog',drawer.includes('role="dialog"'));
check('Drawer aria-modal',drawer.includes('aria-modal="true"'));
check('Drawer cierra con Escape',drawer.includes("e.key==='Escape'"));
const snackbar=read('apps/web/src/design-system/components/Snackbar.jsx');
check('Snackbar aria-live',snackbar.includes('aria-live='));
check('Snackbar alert en error',snackbar.includes("tone==='error'?'alert':'status'"));
const tabs=read('apps/web/src/design-system/components/Tabs.jsx');
check('Tabs tablist',tabs.includes('role="tablist"'));
check('Tabs aria-selected',tabs.includes('aria-selected={selected}'));
const checkbox=read('apps/web/src/design-system/components/Checkbox.jsx'); check('Checkbox nativo accesible',checkbox.includes('type="checkbox"'));
const sw=read('apps/web/src/design-system/components/Switch.jsx'); check('Switch ARIA',sw.includes('role="switch"')&&sw.includes('aria-checked'));
const input=read('apps/web/src/design-system/components/Input.jsx'); check('Input label htmlFor',input.includes('htmlFor={inputId}'));
const select=read('apps/web/src/design-system/components/Select.jsx'); check('Select label htmlFor',select.includes('htmlFor={selectId}'));
const pass=checks.filter(x=>x[1]).length; console.log(`BuzzBee MD3 Accessibility QA v16.0.0\n${pass}/${checks.length} PASS`); for(const [n,o] of checks) console.log(`${o?'PASS':'FAIL'}  ${n}`); if(pass!==checks.length) process.exit(1);
