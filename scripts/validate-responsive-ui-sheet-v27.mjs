import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=p=>readFileSync(path.join(root,p),'utf8');
const styles=read('apps/web/src/design-system/styles/responsive-ui-sheet-v27.css');
const foundation=read('apps/web/src/design-system/styles/foundation.css');
const doc=read('docs/design/business-os-responsive-ui-sheet-v27.md');
const pkg=JSON.parse(read('package.json'));
assert.equal(foundation.split("@import './responsive-ui-sheet-v27.css';").length-1,1,'v27 must import exactly once');
assert.ok(foundation.indexOf('enterprise-ui-v26.css')<foundation.indexOf('responsive-ui-sheet-v27.css'),'v27 must extend existing enterprise layer');
for(const token of ['--bb27-lime','--bb27-charcoal','--bb27-card-radius','--bb27-layout-gap','--bb27-focus'])assert.ok(styles.includes(token),'Missing token '+token);
for(const selector of ["data-kpi-grid","data-kpi-card","data-ux-v19='page-header'","data-ux-v19='filter-bar'","data-ux-v19='smart-table'"])assert.ok(styles.includes(selector),'Missing shared component '+selector);
for(const s of ['min-width:600px','max-width:839px','max-width:599px','max-width:339px','prefers-reduced-motion','min-height:44px','focus-visible'])assert.ok(styles.includes(s),'Missing responsive/accessibility rule '+s);
assert.ok(!styles.includes('display:none!important'),'Do not hide financial or navigation content in v27 layer');
assert.ok(doc.includes('Mobile')||doc.includes('Móvil'),'Design sheet must document mobile');
assert.ok(doc.includes('Tablet'),'Design sheet must document tablet');
assert.equal(pkg.scripts['ui:sheet:audit'],'node scripts/validate-responsive-ui-sheet-v27.mjs');
console.log('PASS Business OS UI sheet v27: web, tablet, mobile, semantics and accessibility patterns');
console.log('NOTE: browser snapshots and physical-device accessibility remain independent gates.');
