import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const auth=read('apps/api/src/modules/core/api/auth.js');
const middleware=read('apps/api/src/middleware/auth.js');
const platform=read('apps/api/src/modules/platform/api/platformAdmin.js');
const schema=read('apps/api/prisma/schema.prisma');
const login=read('apps/web/src/pages/Login.jsx');
const authContext=read('apps/web/src/auth/AuthContext.jsx');
const seed=read('apps/api/prisma/seed.js');
const enable=read('scripts/enable-platform-admin-v13.3.0.mjs');
const checks=[];
const add=(name,ok)=>checks.push({name,ok:Boolean(ok)});
add('MFA fields',schema.includes('mfaEnabled')&&schema.includes('mfaSecretEncrypted'));
add('Session revocation',schema.includes('sessionVersion')&&middleware.includes('sessionVersion !== payload.sv'));
add('Login lockout',schema.includes('failedLoginAttempts')&&auth.includes('USER_LOCK_ATTEMPTS'));
add('IP login rate limit',auth.includes('LOGIN_IP_LIMIT'));
add('TOTP mandatory for platform',auth.includes('mfaRequired')&&auth.includes('/mfa/verify'));
add('MFA enrollment',auth.includes('/mfa/confirm')&&auth.includes('mfaSetupRequired'));
add('Platform session 45m',auth.includes("kind === 'platform' ? '45m' : '8h'"));
add('Platform session middleware',middleware.includes('requirePlatformSession')&&platform.includes('requirePlatformSession'));
add('Critical reauth 10m',middleware.includes('requireRecentReauth')&&platform.includes('requireRecentReauth(600)'));
add('Logout token revocation',auth.includes("sessionVersion:{increment:1}"));
add('Unified login auto-detects Super Admin',login.includes('mfaSetupRequired')&&login.includes('mfaRequired')&&auth.includes('const platform = isPlatformAdmin(user)'));
add('Client cannot choose session context',!auth.includes("z.enum(['erp', 'platform'])")&&!authContext.includes('context: platform'));
add('Legacy admin-login redirects to unified login',read('apps/web/src/App.jsx').includes('path="/admin-login"')&&read('apps/web/src/App.jsx').includes('to="/login"')); 
add('Admin session uses sessionStorage',authContext.includes('PLATFORM_IDLE_MS')&&authContext.includes('platformSession'));
add('15m idle timeout',authContext.includes('15 * 60 * 1000'));
add('Ordinary ERP admin excludes platform.manage',seed.includes("filter((item) => item.key !== 'platform.manage')"));
add('Dedicated Super Admin SaaS role',enable.includes("name: 'Super Admin SaaS'"));
add('Legacy platform grants removed',enable.includes('legacyGrants')&&enable.includes('rolePermission.delete'));
const failed=checks.filter(x=>!x.ok);
for(const c of checks) console.log(`${c.ok?'PASS':'FAIL'}  ${c.name}`);
console.log(`\nPlatform Security: ${checks.length-failed.length}/${checks.length} PASS`);
process.exit(failed.length?1:0);
