import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
const checks=[];
const check=(name,ok)=>{checks.push([name,Boolean(ok)]); console.log(`${ok?'PASS':'FAIL'} · ${name}`)};
const ui=read('apps/web/src/design-system/styles/unified-ui.css');
const reports=read('apps/web/src/modules/operations/ui/pages/Reports.jsx');
const projects=read('apps/web/src/modules/projects/ui/pages/Projects.jsx');
const procurement=read('apps/web/src/modules/procurement/ui/pages/ProcurementCenter.jsx');
const products=read('apps/web/src/modules/inventory/ui/pages/Products.jsx');
const sw=read('apps/web/src/design-system/components/Switch.module.css');
const pos=read('apps/web/src/modules/pos/ui/pages/Pos.module.css');
check('Semantic row surface contract',ui.includes('button[data-ui-surface="row"]'));
check('Semantic icon control contract',ui.includes('button[data-ui-icon="true"]'));
check('Reports snapshot rows marked', (reports.match(/data-ui-surface="row"/g)||[]).length>=5);
check('Projects rail row marked',projects.includes('data-ui-surface="row"'));
check('Procurement action icon accessible',procurement.includes('data-ui-icon="true"')&&procurement.includes('aria-label={`Ver detalle de ${row.folio}`}'));
check('Compact switch variant exists',sw.includes('.small{flex-basis:44px'));
check('Products use compact switch',products.includes('<Switch size="sm" checked={item.active}'));
check('POS desktop ticket height bounded',pos.includes('height:min(690px,calc(100dvh - 145px))'));
const fail=checks.filter(([,ok])=>!ok).length;
console.log(`\nVisual controls v17.5.0: ${checks.length-fail}/${checks.length} PASS`);
process.exitCode=fail?1:0;
