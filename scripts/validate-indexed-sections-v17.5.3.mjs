import fs from 'node:fs';
import path from 'node:path';
const root=process.cwd();
const read=(p)=>fs.readFileSync(path.join(root,p),'utf8');
const checks=[];
const check=(name,ok)=>checks.push([name,Boolean(ok)]);
const ui=read('apps/web/src/design-system/styles/unified-ui.css');
const projectsJs=read('apps/web/src/modules/projects/ui/pages/Projects.jsx');
const projectsCss=read('apps/web/src/modules/projects/ui/pages/Projects.module.css');
const apJs=read('apps/web/src/modules/finance/ui/pages/AccountsPayable.jsx');
const apCss=read('apps/web/src/modules/finance/ui/pages/AccountsPayable.module.css');
const reportsCss=read('apps/web/src/modules/operations/ui/pages/Reports.module.css');
const dataHubCss=read('apps/web/src/modules/operations/ui/pages/DataHub.module.css');
check('Semantic rows no longer force zero padding', !/button\[data-ui-surface="row"\][\s\S]{0,220}padding:0!important/.test(ui));
check('Project selector uses card semantic surface', projectsJs.includes('data-ui-surface="card"') && projectsJs.includes('styles.projectItem'));
check('Project selector has selected-state treatment', projectsCss.includes('indexed section polish · project selector') && projectsCss.includes('.projectList>.selectedProject'));
check('Supplier invoices use safe status fallback', apJs.includes("i.displayStatus||i.status||'PENDING'"));
check('Supplier invoice table has polished row/header contract', apCss.includes('indexed section polish · supplier invoices') && apCss.includes('height:58px'));
check('Operational snapshot rows restore spacing', reportsCss.includes('indexed section polish · operational snapshot') && reportsCss.includes('min-height:48px!important'));
check('Smart Import step 1 has targeted polish', dataHubCss.includes('indexed section polish · Smart Import step 1') && dataHubCss.includes('min-height:230px'));
check('Version is 17.5.3', JSON.parse(read('package.json')).version==='17.5.3' && JSON.parse(read('apps/web/package.json')).version==='17.5.3');
const passed=checks.filter(([,ok])=>ok).length;
for(const [name,ok] of checks) console.log(`${ok?'PASS':'FAIL'} ${name}`);
console.log(`\nIndexed Sections Polish: ${passed}/${checks.length} PASS`);
if(passed!==checks.length) process.exit(1);
